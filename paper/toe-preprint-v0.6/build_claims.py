#!/usr/bin/env python3
"""Generate claims.csv, claimdefs.tex, claims_table.tex, claims_flags.tex, claims_counts.tex and
label_changes.tex (Appendix C) from claims_data.py (stdlib only).

v0.1: every claim carries a source label (x['label'], verbatim from the source) and a paper label
(x['paper'], one of P C E X A F, never stronger than the source). The paper prints the paper label;
the source label is shown in the evidence field whenever it differs."""
import csv, collections
from claims_data import CLAIMS

def esc(s):
    rep = {'\\':r'\textbackslash{}','&':r'\&','%':r'\%','#':r'\#','_':r'\_','{':r'\{','}':r'\}',
           '~':r'\textasciitilde{}','^':r'\textasciicircum{}','$':r'\$','§':r'\S{}','<':r'\textless{}','>':r'\textgreater{}'}
    return ''.join(rep.get(ch, ch) for ch in s)

SEC = dict(s1="§1",s2core="§2.2",s2fit="§2.3",g1="§3.1",g2b="§3.2 B",proof="§3.2 PROOF",g2a="§3.2 A",
           g3="§3.3",g4="§3.4",g5="§3.5",g6="§3.6",fig="§9")

def evidence(x):
    ev = x['evidence']
    if x['paper'] != x['label']:
        ev += '; source label [%s]' % x['label']
    return ev

with open('claims.csv','w',newline='') as f:
    w = csv.writer(f)
    w.writerow(['id','paper label','source label','pending marker','ledger id','short text','evidence pointer'])
    for x in CLAIMS:
        w.writerow([x['id'], x['paper'], x['label'], x['pending'], x['ledger'], x['short'], x['evidence']])

with open('claimdefs.tex','w') as f:
    f.write('% generated by build_claims.py from claims_data.py -- do not edit by hand\n')
    for x in CLAIMS:
        note = r'\footnote{\textbf{Flag (%s):} %s}' % (esc(x['id']), esc(x['note'])) if x['note'] else ''
        unv = r'\unverifiedtag' if x['unverified'] else ''
        pend = r'\pendingtag{%s}' % esc(x['pending']) if x['pending'] else ''
        f.write('\\expandafter\\def\\csname claim@%s\\endcsname{\\claim[%s]{%s}{%s%s%s}{%s}%s}\n' % (
            x['id'], esc(x['id']), x['paper'], x['tex'], unv, pend, esc(evidence(x)), note))

with open('claims_table.tex','w') as f:
    f.write('% generated by build_claims.py -- do not edit by hand\n')
    f.write('\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{0.15\\textwidth}>{\\raggedright\\arraybackslash}p{0.07\\textwidth}>{\\raggedright\\arraybackslash}p{0.13\\textwidth}>{\\raggedright\\arraybackslash}p{0.30\\textwidth}>{\\raggedright\\arraybackslash}p{0.25\\textwidth}@{}}\n')
    f.write('\\toprule ID & Where & Label & Statement (short) & Evidence\\\\\\midrule\\endhead\n')
    for x in CLAIMS:
        lab = '\\claimtag{%s}' % x['paper']
        if x['unverified']: lab += '\\newline\\unverifiedtag'
        if x['paper'] != x['label']: lab += '\\newline{\\tiny source: %s (App.~\\ref{app:labelchanges})}' % esc(x['label'])
        if x['pending']: lab += '\\newline{\\tiny pending ruling}'
        flag = '$^\\ast$' if x['note'] else ''
        f.write('\\scriptsize\\texttt{%s}%s & \\scriptsize %s & %s & \\scriptsize %s & \\scriptsize %s\\\\\n' % (
            esc(x['id']), flag, esc(SEC[x['sec']]), lab, esc(x['short']), esc(evidence(x))))
    f.write('\\bottomrule\\end{longtable}\n')
    f.write('\\noindent{\\footnotesize $^\\ast$ flagged; see Appendix~\\ref{app:flags}.}\n')

with open('claims_flags.tex','w') as f:
    f.write('% generated\n\\begin{itemize}\\small\n')
    for x in CLAIMS:
        if x['note']:
            f.write('\\item \\texttt{%s}: %s\n' % (esc(x['id']), esc(x['note'])))
    f.write('\\end{itemize}\n')

changes = [x for x in CLAIMS if x['paper'] != x['label']]
with open('label_changes.tex','w') as f:
    f.write('% generated by build_claims.py -- do not edit by hand\n')
    f.write('\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{0.03\\textwidth}>{\\raggedright\\arraybackslash}p{0.14\\textwidth}>{\\raggedright\\arraybackslash}p{0.13\\textwidth}>{\\raggedright\\arraybackslash}p{0.08\\textwidth}>{\\raggedright\\arraybackslash}p{0.50\\textwidth}@{}}\n')
    f.write('\\toprule \\# & ID & Source label & Paper label & Reason\\\\\\midrule\\endhead\n')
    for n, x in enumerate(changes, 1):
        reason = esc(x['reason'])
        if x['pending']: reason += ' \\emph{(%s)}' % esc(x['pending'])
        f.write('\\scriptsize %d & \\scriptsize\\texttt{%s} & \\scriptsize [%s] & \\claimtag{%s} & \\scriptsize %s\\\\\n' % (
            n, esc(x['id']), esc(x['label']), x['paper'], reason))
    f.write('\\bottomrule\\end{longtable}\n')

cnt_src = collections.Counter(x['label'] for x in CLAIMS)
cnt_pap = collections.Counter(x['paper'] for x in CLAIMS)
order = 'PCEXAF'
with open('claims_counts.tex','w') as f:
    f.write('%% generated\nTotal labelled claims: %d. By paper label: %s. By source label (verbatim, including non-standard and compound labels): %s. %d claims carry a paper label different from their source label (Appendix~\\ref{app:labelchanges}); %d carry a pending-ruling marker. Of the claims printed [P], %d are hand proofs marked \\unverifiedtag.\n' % (
        len(CLAIMS),
        ', '.join('[%s]~%d' % (k, cnt_pap[k]) for k in order if cnt_pap[k]),
        ', '.join('[%s]~%d' % (esc(k), v) for k, v in sorted(cnt_src.items())),
        len(changes), sum(1 for x in CLAIMS if x['pending']),
        sum(1 for x in CLAIMS if x['unverified'] and x['paper'] == 'P')))
print(len(CLAIMS), 'paper', {k: cnt_pap[k] for k in order}, 'source', dict(cnt_src),
      'changes', len(changes), 'pending', sum(1 for x in CLAIMS if x['pending']),
      'unverified', sum(1 for x in CLAIMS if x['unverified']),
      'unverifiedP', sum(1 for x in CLAIMS if x['unverified'] and x['paper'] == 'P'))
