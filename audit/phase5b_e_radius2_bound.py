def block_form(block, own, fidx):
    """Hermitian Gaussian-integer form of all inter-tile faces inside the cube set `block`; returns (Re, Im) int arrays and tile list."""
    cs = set(block); tiles = sorted({own[q] for q in cs}); loc = {t: i for i, t in enumerate(tiles)}; n = len(tiles)
    Re = np.zeros((2 * n, 2 * n), np.int64); Im = np.zeros((2 * n, 2 * n), np.int64)
    for q in cs:
        for ax in range(3):
            q2 = (q[0] + (ax == 0), q[1] + (ax == 1), q[2] + (ax == 2))
            if q2 not in cs: continue
            t1, t2 = own[q], own[q2]
            if t1 == t2: continue
            C = LINKGI[fidx[t1], fidx[t2], ax]; a, b = loc[t1], loc[t2]
            Re[2*a, 2*a] += 1; Re[2*a+1, 2*a+1] += 1; Re[2*b, 2*b] += 1; Re[2*b+1, 2*b+1] += 1
            Re[2*a:2*a+2, 2*b:2*b+2] -= C[..., 0]; Im[2*a:2*a+2, 2*b:2*b+2] -= C[..., 1]
            Re[2*b:2*b+2, 2*a:2*a+2] -= C[..., 0].T; Im[2*b:2*b+2, 2*a:2*a+2] += C[..., 1].T   # C^dagger
    assert (Re == Re.T).all() and (Im == -Im.T).all()
    return Re, Im, tiles
def lam_min(Re, Im): return 0.0 if Re.shape[0] == 0 else float(np.linalg.eigvalsh(Re + 1j * Im)[0])

def leading_minors_positive(Re, Im, p, q):
    """Exact Sylvester test: is q*(Re + i Im) - p*I positive definite?  Fraction-free Bareiss over Z[i]; the pivots are
    the leading principal minors (real integers for a Hermitian matrix).  Returns (bool, list of minors computed)."""
    n = Re.shape[0]
    A = [[(q * int(Re[i, j]) - (p if i == j else 0), q * int(Im[i, j])) for j in range(n)] for i in range(n)]
    prev = 1; minors = []
    for k in range(n):
        pr, pim = A[k][k]
        assert pim == 0, "diagonal of a Hermitian Bareiss step must be real"
        if pr <= 0: return False, minors
        minors.append(pr)
        for i in range(k + 1, n):
            air, aii = A[i][k]
            for j in range(k + 1, n):
                xr, xi = A[i][j]; bkr, bki = A[k][j]
                # (a_kk a_ij - a_ik a_kj) / prev ,  a_kk real
                nr = pr * xr - (air * bkr - aii * bki); ni = pr * xi - (air * bki + aii * bkr)
                qr, rr = divmod(nr, prev); qi, ri = divmod(ni, prev)
                assert rr == 0 and ri == 0, "Bareiss exact division failed"
                A[i][j] = (qr, qi)
        prev = pr
    return True, minors

