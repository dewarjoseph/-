#!/usr/bin/env python3
"""Phase VII-B (E): per-rule table for the 264 V-D rule classes against the Abelian Z2 benchmark.

Columns: rule index; B_2 (certified radius-2 block lower bound on inf spec(24 - A) for every tiling whose 2-stars are legal for
that rule, phase7_decoration_bounds_shard*.jsonl); census consistency; primitivity of the rule's frame substitution (needed for
completeness of its forward-orbit V_1, hence for B_2 to bound the rule's hull floor); Y_4 (Phase V-D level-4 pinned bottom,
LOBPCG float: an UPPER-side value, compression); status:
  certified_above_Z2     B_2 > U_Z2 (U_Z2 = best certified upper bound on the Z2 hull floor, exact Rayleigh, level 6)
  inconclusive           B_2 <= U_Z2 (the ordering against Z2 rests on uncertified upper-side data only)
  missing                no B_2 result
Usage: python -u -I audit/phase7b_rule_table.py -> audit/results/phase7b_rule_table.json, deliverables/PHASE7_RULE_TABLE.md"""
import os, sys, json, glob
from fractions import Fraction
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE); RES = os.path.join(HERE, 'results'); DEL = os.path.join(HERE, '..', 'deliverables')
import numpy as np
import phase7_local as P
import phase5b_sweep as sw

def primitive(index):
    ops = P.make_ops(sw.decoration(index)); M = np.zeros((P.NG, P.NG), np.int64)
    for f in range(P.NG):
        for g, t in ops: M[f, P.gidx[P.key(P.Gs[f] @ g)]] += 1
    reach = {0}; fr = [0]
    while fr:
        new = {int(j) for i in fr for j in np.nonzero(M[i])[0]} - reach; reach |= new; fr = list(new)
    R = sorted(reach); Mr = M[np.ix_(R, R)]; Mn = np.eye(len(R), dtype=np.int64)
    for n in range(1, 40):
        Mn = np.minimum(Mn @ Mr, 10 ** 6)
        if (Mn > 0).all(): return len(R), n
    return len(R), None

if __name__ == '__main__':
    rules = sorted(json.load(open(os.path.join(RES, 'phase5d_protocol.json')))['rule_indices'])
    B = {}
    for f in glob.glob(os.path.join(RES, 'phase7_decoration_bounds_shard*.jsonl')):
        for l in open(f): r = json.loads(l); B[r['index']] = r
    Y4 = {}
    for f in glob.glob(os.path.join(RES, 'phase5d_features_shard*.jsonl')):
        for l in open(f): r = json.loads(l); Y4[r['index']] = (r['Y4'], r.get('is_fr30', False))
    sc = json.load(open(os.path.join(RES, 'phase7b_scaling.json'))); UZ2 = Fraction(sc['Z2_reflect']['rayleigh_upper_exact'])
    rows = []
    for i in rules:
        nf, pw = primitive(i); r = B.get(i)
        row = {'index': i, 'is_fr30': Y4.get(i, (None, False))[1], 'Y4': Y4.get(i, (None,))[0], 'frames_reachable': nf, 'primitivity_power': pw}
        if r is None: row['status'] = 'missing'
        else:
            b2 = Fraction(r['L2_certified']); row.update({'B2_certified': r['L2_certified'], 'B2': float(b2), 'V1': r['V1'], 'V2': r['V2'],
                                                         'census_T5_subset_V2': r['census_T5_subset_V2']})
            row['status'] = 'certified_above_Z2' if (b2 > UZ2 and pw is not None and r['census_T5_subset_V2']) else 'inconclusive'
        rows.append(row)
    st = {s: sum(1 for r in rows if r['status'] == s) for s in ('certified_above_Z2', 'inconclusive', 'missing')}
    b2s = [r['B2'] for r in rows if 'B2' in r]
    summary = {'rules': len(rows), 'U_Z2_level6': str(UZ2), 'U_Z2_float': float(UZ2), 'status_counts': st, 'B2_min': min(b2s), 'B2_median': float(np.median(b2s)),
               'B2_max': max(b2s), 'all_primitive': all(r['primitivity_power'] is not None for r in rows), 'Y4_min': min(r['Y4'] for r in rows if r['Y4'] is not None),
               'Y4_max': max(r['Y4'] for r in rows if r['Y4'] is not None)}
    json.dump({'summary': summary, 'rows': rows}, open(os.path.join(RES, 'phase7b_rule_table.json'), 'w'), indent=1)
    lines = ['# Phase VII — the 264 V-D rule classes against the Abelian Z₂ benchmark', '',
             f"Generated by `audit/phase7b_rule_table.py`. U_Z₂ = {float(UZ2):.10f} is the exact level-6 Rayleigh upper bound on the reflection-only hull floor.",
             "B₂ is the certified radius-2 block lower bound for the rule; it is valid when the rule's frame substitution is primitive and its V₁ is the complete forward orbit.",
             "Y₄ is the level-4 pinned bottom from Phase V-D, a floating-point value on the upper side.", '',
             f"Summary: {json.dumps(summary)}", '',
             '| rule | FR30 | B₂ (certified) | Y₄ (V-D, upper side) | \\|V₁\\| | \\|V₂\\| | primitive (power) | status |', '|---|---|---|---|---|---|---|---|']
    for r in sorted(rows, key=lambda r: -(r.get('B2') or -1)):
        lines.append(f"| {r['index']} | {'yes' if r['is_fr30'] else ''} | {r.get('B2', float('nan')):.6f} | {r['Y4'] if r['Y4'] is None else round(r['Y4'], 5)} | {r.get('V1', '')} | {r.get('V2', '')} | "
                     f"{r['frames_reachable']} frames, M^{r['primitivity_power']} > 0 | {r['status']} |")
    open(os.path.join(DEL, 'PHASE7_RULE_TABLE.md'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(summary)
