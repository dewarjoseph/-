def exp_support():
    """support principle on the Fibonacci ladder: certified enclosures and the convergence of both sides (Theorem XI.3, D = 1)"""
    out = {}
    for name, X in (('Q8_q1_q2', {'a': Q['q1'], 'b': Q['q2']}), ('Q8_q1_-q1', {'a': Q['q1'], 'b': Q['-q1']}), ('Q8_q1_q1', {'a': Q['q1'], 'b': Q['q1']}),
                    ('Q8_-1_q1', {'a': Q['-1'], 'b': Q['q1']})):
        rows = []
