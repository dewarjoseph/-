def exp_insufficiency():
    """identical Q8 class field (every plaquette in the class {+-q1}) and identical Abelian shadows, different floors:
    Fibonacci (q1, -q1) versus the constant q1 ladder (and versus Fibonacci (q1, q1), which IS the constant ladder)"""
    W = 256; F = subst_factors(FIB, 2 * W); out = {}
    A = {'a': Q['q1'], 'b': Q['-q1']}; B = {'a': Q['q1'], 'b': Q['q1']}
    eA = enclosure(F, A, W); eB = enclosure(F, B, W)
    out['class_field_identical'] = all(q8_class(A[c]) == q8_class(B[c]) for c in 'ab')
    out['shadows_identical'] = True                # chi_k(q1) = chi_k(-q1) for every k: the shadow words coincide letter by letter
    out['A_fib_q1_-q1'] = eA; out['B_const_q1'] = eB
    out['certified_separation'] = (eA['Lambda_certified'] - eB['D_upper']) if eA['Lambda_certified'] > eB['D_upper'] else (eB['Lambda_certified'] - eA['D_upper'])
    out['B_bloch'] = bloch_floor('a', B); log(out); save('insufficiency', out)

