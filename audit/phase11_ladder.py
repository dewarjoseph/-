I2 = np.eye(2, dtype=complex); PAULI = np.array([[[0, 1], [1, 0]], [[0, -1j], [1j, 0]], [[1, 0], [0, -1]]], dtype=complex)
Q = {'1': I2, '-1': -I2, 'q1': -1j * PAULI[0], '-q1': 1j * PAULI[0], 'q2': -1j * PAULI[1], '-q2': 1j * PAULI[1], 'q3': -1j * PAULI[2], '-q3': 1j * PAULI[2]}
def su2(axis, angle):
    """exp(-i angle/2 n.sigma): holonomy angle angle/2 (eigenvalues e^{+-i angle/2})"""
    n = np.array(axis, float); n /= np.linalg.norm(n); return math.cos(angle / 2) * I2 - 1j * math.sin(angle / 2) * np.einsum('i,ijk->jk', n, PAULI)
def adjoint(W): return np.array([[0.5 * np.trace(PAULI[a] @ W @ PAULI[b] @ W.conj().T).real for b in range(3)] for a in range(3)]).astype(complex)
def q8_class(W):
    a = np.trace(W).real / 2
    if np.isclose(a, 1): return '+1'
    if np.isclose(a, -1): return '-1'
    return 'q%d' % (1 + int(np.argmax([abs(np.trace(W @ PAULI[k])) for k in range(3)])))
def hol_angle(W):
    """minimal rotation angle of a unitary: min over eigenvalues e^{i phi} of |phi| (phi in (-pi, pi])"""
    return float(np.min(np.abs(np.angle(np.linalg.eigvals(W)))))

# ------------------------------------------------------------------ languages
def subst_power(sub, w, k):
    for _ in range(k): w = ''.join(sub[c] for c in w)
    return w
def legal_2words(sub, seed='a'):
    """2-letter words of the substitution's language: those of sigma^3(seed), closed under xy -> 2-letter words of sigma(x)sigma(y)
    (complete for a primitive substitution; the analogue of the Phi-closure).  Returns (closure, the subset visible in sigma^3)"""
    w = subst_power(sub, seed, 3); L = {w[i:i + 2] for i in range(len(w) - 1)}; vis = set(L); todo = list(L)
    while todo:
        xy = todo.pop(); s = sub[xy[0]] + sub[xy[1]]
        for i in range(len(s) - 1):
            if s[i:i + 2] not in L: L.add(s[i:i + 2]); todo.append(s[i:i + 2])
    return L, vis
def subst_factors(sub, ell, seed='a'):
    """all factors of length ell of the substitution's language: every factor lies in sigma^k(x)sigma^k(y), xy legal, once every
    sigma^k(c) has length >= ell - 1"""
    L2, _ = legal_2words(sub, seed); k = 0
    while min(len(subst_power(sub, c, k)) for c in sub) < ell - 1: k += 1
    F = set()
    for xy in L2:
        s = subst_power(sub, xy[0], k) + subst_power(sub, xy[1], k)
        for i in range(len(s) - ell + 1): F.add(s[i:i + ell])
    return F
def visible_factors(sub, ell, level, seed='a'):
    """the factors visible in the finite supertile sigma^level(seed) only (the 'training supertile' shortcut)"""
    s = subst_power(sub, seed, level); return {s[i:i + ell] for i in range(len(s) - ell + 1)}
def periodic_factors(period, ell):
    s = period * (ell // len(period) + 2); return {s[i:i + ell] for i in range(len(period))}

# ------------------------------------------------------------------ operators on a window
def window_op(word, X, amp=1.0, diag=3.0, free=False):
    """the pinned operator 3 - A on the window of len(word)+1 columns (rails between consecutive columns carry the letters);
    amp multiplies every rail link (IMS amplification); free: Neumann diagonal (degree inside the window)"""
    k = next(iter(X.values())).shape[0]; ncol = len(word) + 1; nv = 2 * ncol; rows, cols, vals = [], [], []
    def add(a, b, U):
        for s in range(k):
            for t in range(k):
                if U[s, t] != 0: rows.extend([k * a + s, k * b + t]); cols.extend([k * b + t, k * a + s]); vals.extend([-U[s, t], -np.conj(U[s, t])])
    Id = np.eye(k, dtype=complex)
    for n in range(ncol):
        add(2 * n, 2 * n + 1, Id)                                        # rung
        if n + 1 < ncol:
            add(2 * n, 2 * n + 2, amp * Id)                              # bottom rail
            add(2 * n + 1, 2 * n + 3, amp * X[word[n]])                  # top rail
    A = sps.csr_matrix((vals, (rows, cols)), shape=(k * nv, k * nv)); A.sum_duplicates()
    if free:
        deg = np.full(nv, 3.0); deg[[0, 1, nv - 2, nv - 1]] = 2.0
        if ncol == 1: deg[:] = 1.0
        return (sps.diags(np.repeat(deg, k)) + A).tocsr()
    return (diag * sps.identity(k * nv) + A).tocsr()
def lam_min_banded(H, k):
    """lambda_min of a window operator via the banded Hermitian eigensolver (natural ordering has bandwidth 3k - 1)"""
    n = H.shape[0]; b = 3 * k; ab = np.zeros((b + 1, n), complex); Hc = H.tocoo(); m = Hc.row <= Hc.col
    ab[b + Hc.row[m] - Hc.col[m], Hc.col[m]] = Hc.data[m]
    w = sl.eig_banded(ab, lower=False, eigvals_only=True, select='i', select_range=(0, 0)); return float(w[0])
def C1(t):
    """overlap of the 1D Dirichlet ground state cos(pi y/2) on [-1,1] at shift t (exact, 50 digits)"""
    import mpmath as mp
    mp.mp.dps = 50; t = mp.mpf(t.numerator) / t.denominator if isinstance(t, Fraction) else mp.mpf(t); return (1 - t / 2) * mp.cos(mp.pi * t / 2) + mp.sin(mp.pi * t / 2) / mp.pi
def C1_quadrature(t):
    from scipy import integrate
    f = lambda y: math.cos(math.pi * y / 2) * math.cos(math.pi * (y - t) / 2)
    return integrate.quad(f, -1 + t, 1, epsabs=1e-14)[0]

def exact_rayleigh_window(word, X):
    """exact rational upper bound: Rayleigh quotient of the rounded ground vector (entries of X Gaussian integers)"""
    H = window_op(word, X); n = H.shape[0]; k = next(iter(X.values())).shape[0]
    b = 3 * k; ab = np.zeros((b + 1, n), complex); Hc = H.tocoo(); m = Hc.row <= Hc.col; ab[b + Hc.row[m] - Hc.col[m], Hc.col[m]] = Hc.data[m]
    w, V = sl.eig_banded(ab, lower=False, select='i', select_range=(0, 0)); v = V[:, 0] / np.abs(V[:, 0]).max(); s = 2 ** 30
    xr = np.rint(v.real * s).astype(object); xi = np.rint(v.imag * s).astype(object)
    Hr = H.real.tocsr(); Hi = H.imag.tocsr(); assert np.array_equal(Hr.data, np.rint(Hr.data)) and np.array_equal(Hi.data, np.rint(Hi.data))
    Hr = Hr.astype(np.int64); Hi = Hi.astype(np.int64)
    def mv(M, x):
        out = [0] * n
        for r in range(n):
            for idx in range(M.indptr[r], M.indptr[r + 1]): out[r] += int(M.data[idx]) * x[M.indices[idx]]
        return out
    yr = [a - b_ for a, b_ in zip(mv(Hr, xr), mv(Hi, xi))]; yi = [a + b_ for a, b_ in zip(mv(Hr, xi), mv(Hi, xr))]
    num = sum(a * b_ for a, b_ in zip(xr, yr)) + sum(a * b_ for a, b_ in zip(xi, yi)); den = sum(a * a for a in xr) + sum(a * a for a in xi)
    return Fraction(int(num), int(den))

def enclosure(factors, X, W, exact=True, cert=True):
    """the certified pair (Lambda_W, D_W) over the given set of legal 2W-letter environments"""
    k = next(iter(X.values())).shape[0]
    amp = float(1 / C1(Fraction(1, W))); err = 2 * amp * 2.0 ** -52 * 2          # two rails per vertex, |X| entries <= 1
    lp = {w: lam_min_banded(window_op(w, X), k) for w in factors}
    la = {w: lam_min_banded(window_op(w, X, amp=amp), k) for w in factors}
    wD = min(lp, key=lp.get); wL = min(la, key=la.get); out = {'W': W, 'environments': len(factors), 'D_float': lp[wD], 'Lambda_float': la[wL],
                                                               'argmin_D': wD if len(wD) <= 80 else wD[:80] + '...', 'amp': amp, 'ims_bound': 2 * (amp - 1)}
    if cert:
        mu = Fraction(math.floor((la[wL] - 1e-9) * 2 ** 30), 2 ** 30); lows = []
        for w in factors:
            low, _ = C11.banded_cert(window_op(w, X, amp=amp), mu, err); lows.append(low)
        out['Lambda_certified'] = min(lows) if all(l is not None for l in lows) else None
    if exact:
        q = exact_rayleigh_window(wD, X); out['D_exact'] = f'{q.numerator}/{q.denominator}'; out['D_upper'] = float(q)
    return out

def bloch_floor(period, X, grid=64):
    """numerical E_* of a periodic ladder: min over theta of the Bloch matrix of one period (2 len(period) vertices)"""
    k = next(iter(X.values())).shape[0]; p = len(period)
    def lam(th):
        n = 2 * p * k; H = 3 * np.eye(n, dtype=complex)
        def add(a, b, U):
            H[k * a:k * a + k, k * b:k * b + k] -= U; H[k * b:k * b + k, k * a:k * a + k] -= U.conj().T
        for c in range(p):
            add(2 * c, 2 * c + 1, np.eye(k)); ph = np.exp(1j * th) if c == p - 1 else 1.0; nxt = (c + 1) % p
            if p == 1:
                H[0:k, 0:k] -= 2 * math.cos(th) * np.eye(k); H[k:2 * k, k:2 * k] -= (ph * X[period[c]] + np.conj(ph) * X[period[c]].conj().T)
            else:
                add(2 * c, 2 * nxt, ph * np.eye(k)); add(2 * c + 1, 2 * nxt + 1, ph * X[period[c]])
        return float(np.linalg.eigvalsh(H)[0])
    from scipy.optimize import minimize_scalar
    ths = np.linspace(0, 2 * math.pi, grid, endpoint=False); vals = [lam(t) for t in ths]; i = int(np.argmin(vals))
    r = minimize_scalar(lam, bounds=(ths[i] - 2 * math.pi / grid, ths[i] + 2 * math.pi / grid), method='bounded', options={'xatol': 1e-12})
    return min(float(r.fun), min(vals))

