    """no finite radius determines E_*: A_m = (a^m b)^infinity with a = +1 (flat), b = -1.  For m >= 2W all A_m have the same radius-W
    language (every 2W-letter word with at most one b); E_*(A_m) > 0 for every m (flatness radius finite) and E_*(A_m) -> 0"""
