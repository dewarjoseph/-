out = template.replace("-- <<DATA>>", data).replace("<<NP>>", str(nP)).replace("<<NQ>>", str(nQ)).replace("<<N>>", str(N))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'certificates', 'TypeSubstitutionCertificate.lean'), 'w').write(out)
print(f"exported certificates/TypeSubstitutionCertificate.lean: {nP} panel types, {nQ} plaquette types, D={D}")
