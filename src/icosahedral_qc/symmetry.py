"""
src/icosahedral_qc/symmetry.py
================================================================================
Icosahedral Group Symmetries (I_h of order 120 and Chiral I of order 60)
and Acceptance Windows (Achiral W_a, Chiral Triad W_b, -W_b, W_a_scaled).
================================================================================
"""

import itertools
import numpy as np
from scipy.spatial import ConvexHull
from src.icosahedral_qc.projector import P_PAR, P_PERP, PI_PAR

# Generate 6D hyperoctahedral representations that commute with projection
IH_6D = []
I_6D = []

for perm in itertools.permutations(range(6)):
    Pm = np.zeros((6, 6))
    Pm[np.arange(6), perm] = 1.0
    for signs in itertools.product((-1.0, 1.0), repeat=6):
        g = Pm * np.array(signs)[:, None]
        if np.allclose(g @ PI_PAR, PI_PAR @ g, atol=1e-9):
            IH_6D.append(g)
            if np.linalg.det(P_PAR @ g @ P_PAR.T) > 0:
                I_6D.append(g)

# R_perp(g) 3x3 matrices in E_perp
R_PERP_IH = [P_PERP @ g @ P_PERP.T for g in IH_6D]
R_PERP_I = [P_PERP @ g @ P_PERP.T for g in I_6D]

# Canonical seed points
P0_CHIRAL = np.array([0.08, 0.25, 1.48])


def build_acceptance_windows(scale_achiral_to_match_vol=True):
    """
    Constructs the chiral triad of acceptance windows:
      - W_a: Standard achiral triacontahedral window (P_perp applied to [-0.5, 0.5]^6)
      - W_b: Chiral 60-vertex polyhedral window generated by I-orbit of p0
      - -W_b: Mirror enantiomeric polyhedral window (-p0)
    """
    # Achiral window W_a
    hypercube_verts = np.array(list(itertools.product((-0.5, 0.5), repeat=6)))
    hull_a_raw = ConvexHull((P_PERP @ hypercube_verts.T).T)
    
    # Chiral window W_b and mirror -W_b
    verts_b = np.array([R @ P0_CHIRAL for R in R_PERP_I])
    hull_b = ConvexHull(verts_b)
    
    verts_bm = np.array([-R @ P0_CHIRAL for R in R_PERP_I])
    hull_bm = ConvexHull(verts_bm)
    
    if scale_achiral_to_match_vol:
        vol_a = hull_a_raw.volume
        vol_b = hull_b.volume
        scale = (vol_b / vol_a) ** (1.0 / 3.0)
        hull_a = ConvexHull((P_PERP @ (scale * hypercube_verts).T).T)
    else:
        hull_a = hull_a_raw

    return hull_a, hull_b, hull_bm
